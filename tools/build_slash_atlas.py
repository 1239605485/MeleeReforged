#!/usr/bin/env python3
"""Compile CC0 source frames into a tintable, premultiplied RGBA texture."""
from pathlib import Path
import numpy as np
from PIL import Image,ImageFilter
ROOT=Path(__file__).resolve().parents[1]
def build():
    atlas=Image.new('RGBA',(960,320))
    for i in range(6):
        src=Image.open(ROOT/f'assets/slash-study/blue-{i}.png').convert('RGBA')
        tile=Image.new('RGBA',(160,160));tile.alpha_composite(src,((160-src.width)//2,(160-src.height)//2))
        ar=np.array(tile)
        # Neutral luminance retains the source texture's interior pattern.
        value=ar[:,:,:3].max(axis=2)
        ar[:,:,:3]=value[:,:,None]
        tile=Image.fromarray(ar)
        atlas.alpha_composite(tile,(i*160,0))
        atlas.alpha_composite(tile.filter(ImageFilter.GaussianBlur(3)),(i*160,160))
    ar=np.array(atlas).astype('uint16');ar[:,:,:3]=ar[:,:,:3]*ar[:,:,3:4]//255
    # Unity raw upload is bottom-up. XNA source rectangles remain top-down.
    data=ar.astype('uint8')[::-1].tobytes()
    target=ROOT/'src/generated/slash_atlas.hpp';target.parent.mkdir(exist_ok=True)
    with target.open('w') as f:
        f.write('// Generated by tools/build_slash_atlas.py; Cethiel, CC0.\n#pragma once\nnamespace mr {\ninline constexpr int slashAtlasWidth=960,slashAtlasHeight=320;\ninline constexpr unsigned char slashAtlasPixels[]={\n')
        for start in range(0,len(data),32):f.write(','.join(map(str,data[start:start+32]))+',\n')
        f.write('};\n}\n')
if __name__=='__main__':build()
